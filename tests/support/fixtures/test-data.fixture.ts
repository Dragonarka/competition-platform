import { nanoid } from 'nanoid';

export interface CompetitionSeed {
  id: string;
  name: string;
  description: string;
  date: string;
}

export interface CriterionSeed {
  name: string;
  minScore: string;
  maxScore: string;
}

export interface ParticipantSeed {
  participantId: string;
  name: string;
}

export const competitionFactory = {
  build(overrides: Partial<CompetitionSeed> = {}): CompetitionSeed {
    const id = nanoid(21);
    return {
      id,
      name: `E2E Competition ${id.slice(0, 8)}`,
      description: 'Auto-generated by Playwright fixture',
      date: new Date().toISOString(),
      ...overrides,
    };
  },
};

export const criterionFactory = {
  build(overrides: Partial<CriterionSeed> = {}): CriterionSeed {
    const idx = Math.floor(Math.random() * 1000);
    return {
      name: `Criterion ${idx}`,
      minScore: '0.00',
      maxScore: '10.00',
      ...overrides,
    };
  },
  buildMany(count: number, overrides: Partial<CriterionSeed> = {}): CriterionSeed[] {
    const defaultNames = ['Musicality', 'Technique', 'Creativity', 'Stage Presence', 'Originality'];
    return Array.from({ length: count }, (_, i) =>
      criterionFactory.build({
        name: defaultNames[i] ?? `Criterion ${i + 1}`,
        ...overrides,
      }),
    );
  },
};

export const participantFactory = {
  build(overrides: Partial<ParticipantSeed> = {}): ParticipantSeed {
    const n = Math.floor(Math.random() * 10000);
    return {
      participantId: `P-${n.toString().padStart(4, '0')}`,
      name: `Competitor ${n}`,
      ...overrides,
    };
  },
  buildMany(count: number): ParticipantSeed[] {
    return Array.from({ length: count }, (_, i) =>
      participantFactory.build({
        participantId: `P-${(i + 1).toString().padStart(4, '0')}`,
        name: `Competitor ${(i + 1).toString().padStart(2, '0')}`,
      }),
    );
  },
};

export function uniqueSuffix(): string {
  return nanoid(8);
}
